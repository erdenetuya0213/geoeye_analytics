export type StereonetThemeId = (typeof stereonetThemes)[number]['id']
export type StereonetTheme = (typeof stereonetThemes)[number]

export const DEFAULT_STEREONET_THEME: StereonetThemeId = 'geoeye-console'

export function isStereonetThemeId(value: string | null): value is StereonetThemeId {
  return stereonetThemes.some((theme) => theme.id === value)
}

export function stereonetThemeById(id: StereonetThemeId): StereonetTheme {
  return stereonetThemes.find((theme) => theme.id === id) ?? stereonetThemes[0]
}
